"""
feast/feature_views.py
───────────────────────
V2 Feast feature definitions.

What changed from V1:
  V1: FileSource pointing to a local synthetic parquet generated by
      generate_sample_features() — no real data, no R2 integration.
  V2:
    - Offline store: R2-backed Parquet files written by DataAgent per workflow.
      The FileSource path is resolved at materialize time from the workflow-
      specific parquet written by DataAgent._materialize_features().
    - Online store: Redis (same connection string as settings.feast_redis_connection_string)
    - Feature views are registered here statically; DataAgent adds dynamic
      per-dataset views via register_dynamic_feature_view() below.
    - entity key: record_id (Int64) — stable join key written by DataAgent.
    - TTLs: 1-day for high-churn numeric features, 7-day for entity metadata.

Apply with:
    feast apply

Materialize (called by DataAgent._materialize_features, not manually):
    feast materialize-incremental $(date -u +"%Y-%m-%dT%H:%M:%S")

Verify online store (Redis health check):
    feast feature-store status
"""

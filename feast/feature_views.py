# Training feature retrieval (used by TrainingAgent in Phase 2) 
def get_training_features(
    store: FeatureStore,
    entity_df: pd.DataFrame,
    feature_refs: Optional[list[str]] = None,
) -> pd.DataFrame:
    if feature_refs is None:
        feature_refs = [
            f"numeric_features:{f.name}"
            for f in numeric_features_fv.schema
        ] + [
            "entity_metadata:category",
            "entity_metadata:label",
        ]

    logger.info(
        "Retrieving %d historical features for %d entities",
        len(feature_refs), len(entity_df),
    )
    return store.get_historical_features(
        entity_df=entity_df,
        features=feature_refs,
    ).to_df()


def get_online_features(
    store: FeatureStore,
    record_ids: list[int],
    feature_refs: Optional[list[str]] = None,
) -> pd.DataFrame:
    if feature_refs is None:
        feature_refs = [
            f"numeric_features:{f.name}"
            for f in numeric_features_fv.schema
        ]

    entity_rows = [{"record_id": rid} for rid in record_ids]
    response = store.get_online_features(
        features=feature_refs,
        entity_rows=entity_rows,
    ).to_dict()

    return pd.DataFrame(response)


# Dynamic feature view registration
def register_dynamic_feature_view(
    store: FeatureStore,
    dataset_id: str,
    df: pd.DataFrame,
    source_path: str,
    ttl_days: int = 1,
) -> FeatureView:
    """
    Register a FeatureView whose schema is derived from the REAL ingested
    dataframe's own columns/dtypes, backed by the REAL per-workflow Parquet
    file DataAgent just wrote (source_path) — not the synthetic dev fixture.

    Called by DataAgent._materialize_features() on every ingestion so Feast
    actually serves what was ingested, instead of only ever serving
    generate_dev_fixture()'s synthetic f0..f19 columns.
    """
    from feast.types import Float32, Float64, Int64, String

    _pandas_to_feast = {
        "float32": Float32,
        "float64": Float64,
        "int32":   Int64,
        "int64":   Int64,
        "object":  String,
        "string":  String,
        "bool":    Int64,     # Feast does not have a native Bool type in all versions
    }

    # Build fields from DataFrame dtypes, skip Feast metadata columns
    _feast_reserved = {"record_id", "event_timestamp", "created_timestamp"}
    fields = []
    for col in df.columns:
        if col in _feast_reserved:
            continue
        dtype_str = str(df[col].dtype)
        feast_type = _pandas_to_feast.get(dtype_str, String)
        fields.append(Field(name=col, dtype=feast_type))

    if not fields:
        logger.warning(
            "register_dynamic_feature_view: no non-reserved columns found in df for %s",
            dataset_id,
        )
        return numeric_features_fv   # fallback to static view

    source = FileSource(
        path=source_path,
        timestamp_field="event_timestamp",
    )

    fv = FeatureView(
        name=f"{dataset_id}_features",
        entities=[record],
        ttl=timedelta(days=ttl_days),
        schema=fields,
        source=source,
        tags={"team": "mlops", "dataset_id": dataset_id, "auto_generated": "true"},
        online=True,
    )

    # Apply the new view to the store
    store.apply([record, fv])
    logger.info(
        "Dynamic FeatureView registered: name=%s fields=%d ttl_days=%d source=%s",
        fv.name, len(fields), ttl_days, source_path,
    )
    return fv

def generate_dev_fixture(
    output_path: Optional[str] = None,
    n_rows: int = 2000,
    n_numeric_features: int = 20,
) -> str:
    """
    Write a development fixture parquet with schema matching the static feature views.

    In production the DataAgent writes real ingested data here.
    This fixture exists only so engineers can run `feast apply` locally
    without needing real R2 credentials.

    Returns the path written.
    """
    import numpy as np
    from datetime import datetime, timezone

    output_path = output_path or str(_OFFLINE_DATA_DIR / "features_dev_fixture.parquet")
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    rng = np.random.default_rng(seed=42)
    data: dict = {}
    for i in range(n_numeric_features):
        data[f"f{i}"] = rng.standard_normal(n_rows).astype("float32")

    data["record_id"]       = list(range(n_rows))
    data["label"]           = rng.integers(0, 2, size=n_rows).tolist()
    data["category"]        = rng.choice(["A", "B", "C"], size=n_rows).tolist()
    data["source"]          = ["dev_fixture"] * n_rows
    data["row_count"]       = [n_rows] * n_rows
    data["split"]           = rng.choice(["train", "val"], p=[0.8, 0.2], size=n_rows).tolist()
    data["dataset_version"] = ["1.0.0"] * n_rows
    data["workflow_id"]     = ["dev_fixture"] * n_rows
    data["event_timestamp"] = [datetime.now(timezone.utc)] * n_rows

    df = pd.DataFrame(data)
    df.to_parquet(output_path, index=False)
    logger.info("Dev fixture written: path=%s rows=%d", output_path, n_rows)
    print(f"✅ Dev fixture written: {output_path} ({n_rows} rows)")
    return output_path


